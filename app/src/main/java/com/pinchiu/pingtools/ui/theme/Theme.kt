private const val THEME_PREFS = "pingtools_theme"
private const val THEME_KEY = "mode"

/** 0 = system, 1 = light, 2 = dark */
object ThemeStore {
    fun read(context: Context): Int =
        context.getSharedPreferences(THEME_PREFS, Context.MODE_PRIVATE).getInt(THEME_KEY, 0)

    fun write(context: Context, mode: Int) {
        context.getSharedPreferences(THEME_PREFS, Context.MODE_PRIVATE)
            .edit().putInt(THEME_KEY, mode).apply()
    }
}

@Composable
fun PingToolsTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = AppTypography,
        content = content
    )
}
